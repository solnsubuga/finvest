"""Build one release bundle for deploy.sh from the GitHub environment's settings.

Ported from Fidiba's scripts/prepare_deployment.py. Each process gets a runtime file with only its
own database role, so the schema owner's password never reaches the API, worker or scheduler.
Settings are read from the environment (the deploy workflow passes them) and validated before
anything is written. Nothing secret is printed.

    python3 infra/deployment/prepare_release.py OUTPUT_DIR
"""

from __future__ import annotations

import argparse
import base64
import json
import os
import re
import shutil
import stat
import sys
from collections.abc import Mapping
from pathlib import Path
from urllib.parse import quote

HERE = Path(__file__).resolve().parent
ENVIRONMENTS = ("staging", "production")
# Caddy and each colour's api and console meet on this network. The API believes X-Forwarded-For
# only from it (FINVEST_TRUSTED_PROXIES), and only Caddy sets that header.
EDGE_SUBNET = "172.30.0.0/24"
CA_PATH = "/etc/finvest/database-ca/ca.crt"
# The phone apps' identities, for passkeys on the website's domain (docs/sign-in.md).
APPLE_TEAM_ID = r"[A-Z0-9]{10}"
ANDROID_CERT_SHA256 = r"[0-9A-F]{2}(:[0-9A-F]{2}){31}"
HOSTNAME = r"[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+"
IMAGE = r"[a-z0-9.:/_-]+@sha256:[a-f0-9]{64}"
ROLES = {"migrate": "migrator", "api": "app", "worker": "worker", "scheduler": "worker"}


class SettingError(ValueError):
    pass


def setting(env: Mapping[str, str], name: str, default: str | None = None, pattern: str | None = None) -> str:
    """A required setting, or its default, checked against a pattern. Values never appear in errors."""
    value = env.get(name, "").strip() or default
    if value is None or value == "":
        raise SettingError(f"{name} is not set")
    if pattern is not None and not re.fullmatch(pattern, value):
        raise SettingError(f"{name} is not valid")
    return value


def optional(env: Mapping[str, str], name: str) -> str:
    return env.get(name, "").strip()


def single_line(name: str, value: str) -> str:
    if "\n" in value or "\r" in value or "\0" in value:
        raise SettingError(f"{name} must be one line")
    return value


def private_write(path: Path, text: str, mode: int = 0o600) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write(text)
    os.chmod(path, mode)


def env_file(values: Mapping[str, str]) -> str:
    # Compose reads these with format: raw, so values are taken verbatim to the end of the line.
    return "".join(f"{name}={single_line(name, value)}\n" for name, value in values.items())


def database_url(env: Mapping[str, str], role: str) -> str:
    host = setting(env, "DATABASE_HOST", pattern=r"[a-zA-Z0-9][a-zA-Z0-9.-]*")
    port = setting(env, "DATABASE_PORT", "25060", r"[0-9]{1,5}")
    name = setting(env, "DATABASE_NAME", "finvest", r"[a-z_][a-z0-9_]*")
    password = single_line(f"DATABASE_{role.upper()}_PASSWORD", setting(env, f"DATABASE_{role.upper()}_PASSWORD"))
    return f"postgresql+asyncpg://finvest_{role}:{quote(password, safe='')}@{host}:{port}/{name}"


def passkey_app_origins(env: Mapping[str, str], client_site: str) -> str:
    """The origins the phone apps sign passkeys from: the website's for iPhone, and one
    android:apk-key-hash per signing certificate. None until the store accounts exist."""
    team_id = optional(env, "APPLE_TEAM_ID")
    if team_id and not re.fullmatch(APPLE_TEAM_ID, team_id):
        raise SettingError("APPLE_TEAM_ID is not valid")
    certs = [c.strip() for c in optional(env, "ANDROID_CERT_SHA256").split(",") if c.strip()]
    for cert in certs:
        if not re.fullmatch(ANDROID_CERT_SHA256, cert):
            raise SettingError("ANDROID_CERT_SHA256 is not valid")
    if not team_id and not certs:
        return "[]"
    origins = [f"https://{client_site}"]
    for cert in certs:
        digest = base64.urlsafe_b64encode(bytes.fromhex(cert.replace(":", ""))).decode().rstrip("=")
        origins.append(f"android:apk-key-hash:{digest}")
    return json.dumps(origins)


def site_caddy(site_domains: list[str], published: bool, listed: bool) -> str:
    canonical, *others = site_domains
    # Only the production website may be listed by search engines. The pages themselves also
    # carry noindex until the site is built with PUBLIC_INDEXABLE=true.
    unlisted = "" if listed else "\timport unlisted\n"
    if published:
        text = (
            "# Generated by prepare_release.py. The public website (site.Dockerfile).\n"
            f"{canonical} {{\n"
            "\timport origin_tls\n"
            "\timport updating\n"
            "\timport common_headers\n"
            f"{unlisted}"
            "\tencode zstd gzip\n"
            "\t# The site image sends the policy written for its own pages (site-csp.mjs). This one\n"
            "\t# applies only if a response arrives without it.\n"
            "\theader ?Content-Security-Policy \"default-src 'self'; object-src 'none'; "
            "base-uri 'self'; frame-ancestors 'none'\"\n"
            "\troute {\n"
            "\t\timport private_paths\n"
            "\t\timport site_upstream\n"
            "\t}\n"
            "}\n"
        )
    else:
        text = (
            "# Generated by prepare_release.py. The public website is not published here yet.\n"
            f"{canonical} {{\n"
            "\timport origin_tls\n"
            "\timport common_headers\n"
            "\timport unlisted\n"
            "\t# The phone apps read these two files to use passkeys on this domain, published or not.\n"
            "\t@app_links path /.well-known/apple-app-site-association /.well-known/assetlinks.json\n"
            "\thandle @app_links {\n"
            "\t\timport site_upstream\n"
            "\t}\n"
            "\thandle {\n"
            "\t\theader Cache-Control no-store\n"
            "\t\theader Content-Security-Policy \"default-src 'none'; frame-ancestors 'none'\"\n"
            '\t\trespond "Finvest\'s new website is on its way." 503\n'
            "\t}\n"
            "}\n"
        )
    if others:
        text += (
            f"{', '.join(others)} {{\n"
            "\timport origin_tls\n"
            "\timport common_headers\n"
            f"\tredir https://{canonical}{{uri}} 308\n"
            "}\n"
        )
    return text


def email_backend(env: Mapping[str, str]) -> str:
    """The email backend the worker is given. Production sends through Resend unless
    FINVEST_EMAIL_BACKEND says otherwise (the owner's default). It stays off when the sender or key
    is missing, because the worker refuses to start with Resend and no key. Staging and local
    rehearsals keep whatever is set, which is off when blank."""
    chosen = optional(env, "FINVEST_EMAIL_BACKEND")
    production = optional(env, "DEPLOY_ENVIRONMENT") == "production" and optional(env, "FINVEST_REHEARSAL") != "true"
    if chosen or not production:
        return chosen
    if optional(env, "FINVEST_EMAIL_FROM") and optional(env, "FINVEST_EMAIL_RESEND_API_KEY"):
        return "resend"
    return ""


def email_warnings(env: Mapping[str, str]) -> list[str]:
    """Why a production release would send no email. The deploy still goes ahead (the owner's call),
    but with email off the worker queues every message without failing anything, so the run says
    so loudly. Staging and local rehearsals may leave email off."""
    if optional(env, "DEPLOY_ENVIRONMENT") != "production" or optional(env, "FINVEST_REHEARSAL") == "true":
        return []
    warnings = []
    if optional(env, "FINVEST_EMAIL_BACKEND") not in ("", "resend"):
        warnings.append("FINVEST_EMAIL_BACKEND is not resend, so production will send no email")
    if not optional(env, "FINVEST_EMAIL_FROM"):
        warnings.append("FINVEST_EMAIL_FROM is not set, so production will send no email")
    if not optional(env, "FINVEST_EMAIL_RESEND_API_KEY"):
        warnings.append("FINVEST_RESEND_API_KEY is not set, so production will send no email")
    return warnings


def prepare(output: Path, env: Mapping[str, str]) -> None:
    environment = setting(env, "DEPLOY_ENVIRONMENT", pattern="|".join(ENVIRONMENTS))
    rehearsal = optional(env, "FINVEST_REHEARSAL") == "true"

    api_domain = setting(env, "API_DOMAIN", pattern=HOSTNAME)
    admin_domain = setting(env, "ADMIN_DOMAIN", pattern=HOSTNAME)
    app_domain = setting(env, "APP_DOMAIN", pattern=HOSTNAME)
    site_domains = [d for d in re.split(r"[\s,]+", setting(env, "SITE_DOMAINS")) if d]
    for domain in site_domains:
        if not re.fullmatch(HOSTNAME, domain):
            raise SettingError("SITE_DOMAINS is not valid")
    hosts = [api_domain, admin_domain, app_domain, *site_domains]
    if len(set(hosts)) != len(hosts):
        raise SettingError("Every domain must be different")

    backend_image = setting(env, "BACKEND_IMAGE", pattern=IMAGE)
    console_image = setting(env, "CONSOLE_IMAGE", pattern=IMAGE)
    app_image = setting(env, "APP_IMAGE", pattern=IMAGE)
    site_image = setting(env, "SITE_IMAGE", pattern=IMAGE)
    # Staging always serves the website. Production serves it only once the owner launches it
    # (SITE_PUBLISHED=true).
    site_published = environment != "production" or optional(env, "SITE_PUBLISHED") == "true"
    project = f"finvest-{environment}"
    # A rehearsal turns database TLS off, so it is accepted only with images from the throwaway
    # registry on the same machine, which a real deployment never uses.
    if rehearsal and not all(
        image.startswith("localhost:") for image in (backend_image, console_image, app_image, site_image)
    ):
        raise SettingError("FINVEST_REHEARSAL is for a local rehearsal only")

    origin_cert = setting(env, "ORIGIN_TLS_CERT")
    origin_key = setting(env, "ORIGIN_TLS_KEY")
    if "BEGIN CERTIFICATE" not in origin_cert or "PRIVATE KEY" not in origin_key:
        raise SettingError("ORIGIN_TLS_CERT and ORIGIN_TLS_KEY must be PEM")
    ca_cert = optional(env, "DATABASE_CA_CERT")
    if ca_cert and "BEGIN CERTIFICATE" not in ca_cert:
        raise SettingError("DATABASE_CA_CERT must be PEM")
    if not ca_cert and not rehearsal:
        raise SettingError("DATABASE_CA_CERT is not set")

    # Validate every database setting before writing anything.
    urls = {service: database_url(env, role) for service, role in ROLES.items()}

    # Every process is told which environment it runs in, so code that must never run in
    # production (a sandbox payment provider, for one) can refuse to start there.
    database = {"FINVEST_ENVIRONMENT": environment, "FINVEST_LOG_FORMAT": "json"}
    if rehearsal:
        database["FINVEST_DATABASE_SSL_MODE"] = "disable"
    else:
        database["FINVEST_DATABASE_SSL_MODE"] = "verify-full"
        database["FINVEST_DATABASE_SSL_ROOT_CERT"] = CA_PATH

    storage = {
        name: single_line(name, optional(env, name))
        for name in (
            "FINVEST_OBJECT_STORAGE_BUCKET",
            "FINVEST_OBJECT_STORAGE_ENDPOINT",
            "FINVEST_OBJECT_STORAGE_REGION",
            "FINVEST_OBJECT_STORAGE_ACCESS_KEY_ID",
            "FINVEST_OBJECT_STORAGE_SECRET_ACCESS_KEY",
        )
        if optional(env, name)
    }
    # Files go to the private bucket (backend app/infrastructure/storage) only when the whole
    # bucket setting is there. Anything less leaves storage off, and uploads fail closed.
    storage_origin = ""
    if len(storage) == 5:
        bucket = storage["FINVEST_OBJECT_STORAGE_BUCKET"]
        endpoint = storage["FINVEST_OBJECT_STORAGE_ENDPOINT"]
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]{1,61}[a-z0-9]", bucket):
            raise SettingError("FINVEST_OBJECT_STORAGE_BUCKET is not valid")
        if not re.fullmatch(rf"https://{HOSTNAME}", endpoint):
            raise SettingError("FINVEST_OBJECT_STORAGE_ENDPOINT is not valid")
        storage["FINVEST_OBJECT_STORAGE_BACKEND"] = "s3"
        # Staff open files through short-lived read links on the bucket's own address.
        storage_origin = f"https://{bucket}.{endpoint.removeprefix('https://')}"

    # Sign-in settings (backend identity module). The client passkey site is the zone in
    # production, so passkeys work on the web and in the phone apps; staging keeps its own.
    client_site = site_domains[0] if environment == "production" else app_domain
    api = {
        **database,
        "FINVEST_DATABASE_URL": urls["api"],
        "FINVEST_TRUSTED_PROXIES": json.dumps([EDGE_SUBNET]),
        "FINVEST_CLIENT_ALLOWED_ORIGINS": json.dumps([f"https://{app_domain}"]),
        "FINVEST_STAFF_ALLOWED_ORIGINS": json.dumps([f"https://{admin_domain}"]),
        "FINVEST_CLIENT_PASSKEY_SITE": client_site,
        "FINVEST_STAFF_PASSKEY_SITE": admin_domain,
        "FINVEST_CLIENT_PASSKEY_APP_ORIGINS": passkey_app_origins(env, client_site),
        **storage,
    }
    # Client sign-up stays closed unless this is exactly "true": production until switch day,
    # staging except during the pen test weeks (docs/launch.md).
    api["FINVEST_CLIENT_SIGNUP_OPEN"] = "true" if optional(env, "FINVEST_CLIENT_SIGNUP_OPEN") == "true" else "false"
    if optional(env, "FINVEST_AUTHENTICATOR_KEY"):
        api["FINVEST_AUTHENTICATOR_KEY"] = optional(env, "FINVEST_AUTHENTICATOR_KEY")

    worker = {**database, "FINVEST_DATABASE_URL": urls["worker"], **storage}
    # Keys the hash under which email addresses are kept on the suppression list and in delivery
    # events. The API records events and lift proposals, the worker applies them.
    if optional(env, "FINVEST_EMAIL_HASH_KEY"):
        api["FINVEST_EMAIL_HASH_KEY"] = optional(env, "FINVEST_EMAIL_HASH_KEY")
        worker["FINVEST_EMAIL_HASH_KEY"] = optional(env, "FINVEST_EMAIL_HASH_KEY")
    # Encrypts clients' identity details. The API and the worker read it; nothing else gets it.
    if optional(env, "FINVEST_IDENTITY_DATA_KEY"):
        api["FINVEST_IDENTITY_DATA_KEY"] = optional(env, "FINVEST_IDENTITY_DATA_KEY")
        worker["FINVEST_IDENTITY_DATA_KEY"] = optional(env, "FINVEST_IDENTITY_DATA_KEY")
    # The signing secret of the webhook in Finvest's own Resend account. The API checks each delivery
    # event with it; nothing else needs it.
    if optional(env, "RESEND_HOOK_SECRET"):
        api["RESEND_HOOK_SECRET"] = optional(env, "RESEND_HOOK_SECRET")
    # The secret in the address Africa's Talking posts SMS delivery reports to. Only the API
    # answers that address.
    if optional(env, "FINVEST_SMS_AFRICASTALKING_CALLBACK_TOKEN"):
        api["FINVEST_SMS_AFRICASTALKING_CALLBACK_TOKEN"] = optional(
            env, "FINVEST_SMS_AFRICASTALKING_CALLBACK_TOKEN"
        )
    if email_backend(env):
        worker["FINVEST_EMAIL_BACKEND"] = email_backend(env)
    for name in (
        "FINVEST_EMAIL_FROM",
        "FINVEST_EMAIL_RESEND_API_KEY",
        # SMS goes out from the worker only (backend app/infrastructure/sms).
        "FINVEST_SMS_BACKEND",
        "FINVEST_SMS_FALLBACK",
        "FINVEST_SMS_AFRICASTALKING_USERNAME",
        "FINVEST_SMS_AFRICASTALKING_API_KEY",
        "FINVEST_SMS_AFRICASTALKING_SENDER_ID",
        "FINVEST_SMS_AFRICASTALKING_BASE_URL",
        "FINVEST_SMS_IOTEC_CLIENT_ID",
        "FINVEST_SMS_IOTEC_API_KEY",
        "FINVEST_SMS_IOTEC_BASE_URL",
    ):
        if optional(env, name):
            worker[name] = optional(env, name)

    scheduler = {**database, "FINVEST_DATABASE_URL": urls["scheduler"]}
    # ioTec Pay (backend payments and payouts, docs/payments.md) and ioTec Verify (identity checks,
    # docs/identity-checks.md). Each setting goes only to the processes that read it.
    for names, targets in (
        # The scheduler reads which provider and currency to plan for, and holds no credentials.
        (("FINVEST_PAYMENTS_PROVIDER", "FINVEST_IOTEC_CURRENCY_CODE"), (api, worker, scheduler)),
        (
            (
                "FINVEST_IOTEC_CLIENT_ID",
                "FINVEST_IOTEC_CLIENT_SECRET",
                "FINVEST_IOTEC_WALLET_ID",
                "FINVEST_IOTEC_TOKEN_URL",
                "FINVEST_IOTEC_PAY_URL",
                "FINVEST_IOTEC_TIMEOUT_SECONDS",
                "FINVEST_IDENTITY_PROVIDER",
                "FINVEST_IOTEC_VERIFY_CLIENT_ID",
                "FINVEST_IOTEC_VERIFY_API_KEY",
                "FINVEST_IOTEC_VERIFY_BASE_URL",
            ),
            (api, worker),
        ),
        # The worker reads the name a network holds for a payout number (ioTec Verify, with the
        # FINVEST_IOTEC_VERIFY_* credentials above). The API reads the provider too, to tell whether
        # a new number waits for that check or for proof.
        (("FINVEST_PAYOUT_NAME_PROVIDER",), (api, worker)),
        # Sanctions and PEP screening (docs/screening.md). The worker runs the screens; the API reads
        # the provider to decide whether a payout waits for one.
        (
            (
                "FINVEST_SCREENING_PROVIDER",
                "FINVEST_SIGMA360_API_KEY",
                "FINVEST_SIGMA360_FILTER_SET_ID",
                "FINVEST_SIGMA360_BASE_URL",
            ),
            (api, worker),
        ),
        # Custodian statement checks (PR 568): uploads are read by the API and the worker. Unset, the
        # reader is off and uploads answer 503 custodian_reading_off.
        (
            (
                "FINVEST_CUSTODIAN_READER",
                "FINVEST_ANTHROPIC_API_KEY",
                "FINVEST_OPENAI_API_KEY",
                "FINVEST_GEMINI_API_KEY",
                "FINVEST_CUSTODIAN_READER_MODEL",
            ),
            (api, worker),
        ),
        # The worker keeps the back office's Cloudflare Access list in step with console Team
        # changes. The list and account come from Terraform; the token is the owner's.
        (
            (
                "FINVEST_CLOUDFLARE_ACCOUNT_ID",
                "FINVEST_CLOUDFLARE_STAFF_LIST_ID",
                "FINVEST_CLOUDFLARE_ACCESS_TOKEN",
            ),
            (worker,),
        ),
        # Checks ioTec's collection callbacks, which only the API receives.
        (("FINVEST_IOTEC_CALLBACK_TOKEN",), (api,)),
        # Card payments (docs/payments.md). The scheduler reads only the provider and Pesapal's
        # address, for its start-up checks; the API and the worker talk to Pesapal.
        (("FINVEST_CARDS_PROVIDER", "FINVEST_PESAPAL_BASE_URL"), (api, worker, scheduler)),
        (
            (
                "FINVEST_PESAPAL_CONSUMER_KEY",
                "FINVEST_PESAPAL_CONSUMER_SECRET",
                "FINVEST_PESAPAL_IPN_TOKEN",
                "FINVEST_PESAPAL_TIMEOUT_SECONDS",
            ),
            (api, worker),
        ),
    ):
        for name in names:
            if optional(env, name):
                for target in targets:
                    target[name] = single_line(name, optional(env, name))
    # Pesapal calls this environment's own API and sends the payer back to its own app, so
    # staging never points Pesapal at production. A value set by hand still wins.
    if optional(env, "FINVEST_CARDS_PROVIDER") == "pesapal":
        for name, value in (
            ("FINVEST_PESAPAL_PUBLIC_API_URL", f"https://{api_domain}"),
            ("FINVEST_PESAPAL_RETURN_URL", f"https://{app_domain}/pay/card/return"),
        ):
            chosen = single_line(name, optional(env, name) or value)
            api[name] = chosen
            worker[name] = chosen

    runtime = {
        "migrate": {**database, "FINVEST_DATABASE_URL": urls["migrate"]},
        "api": api,
        "worker": worker,
        "scheduler": scheduler,
    }

    release = {
        "FINVEST_DEPLOY_PROJECT": project,
        "BACKEND_IMAGE": backend_image,
        "CONSOLE_IMAGE": console_image,
        "APP_IMAGE": app_image,
        "SITE_IMAGE": site_image,
        "FINVEST_API_DOMAIN": api_domain,
        "FINVEST_ADMIN_DOMAIN": admin_domain,
        "FINVEST_APP_DOMAIN": app_domain,
        "FINVEST_EDGE_SUBNET": EDGE_SUBNET,
        "FINVEST_STORAGE_ORIGIN": storage_origin,
        "FINVEST_STOP_BEFORE_MIGRATE": "true" if optional(env, "STOP_BEFORE_MIGRATE") == "true" else "false",
    }
    if site_published:
        # deploy.sh checks the website through its public address only when it is served.
        release["FINVEST_SITE_DOMAIN"] = site_domains[0]
    if rehearsal:
        release["FINVEST_CHECK_LOCAL"] = "true"
        for name in ("FINVEST_HTTP_PORT", "FINVEST_HTTPS_PORT", "FINVEST_BIND_ADDRESS"):
            if optional(env, name):
                release[name] = optional(env, name)

    if output.exists():
        shutil.rmtree(output)
    output.mkdir(mode=0o700, parents=True)
    for name in ("compose.yaml", "deploy.sh"):
        shutil.copy(HERE / name, output / name)
    (output / "deploy.sh").chmod(stat.S_IRWXU)
    (output / "edge").mkdir(mode=0o755)
    for name in ("Caddyfile", "upstreams.caddy"):
        shutil.copy(HERE / name, output / "edge" / name)
    (output / "edge" / "site.caddy").write_text(site_caddy(site_domains, site_published, listed=environment == "production"), encoding="utf-8")
    private_write(output / "release.env", env_file(release))
    for service, values in runtime.items():
        private_write(output / "runtime" / f"{service}.env", env_file(values))
    (output / "database-ca").mkdir(mode=0o755)
    if ca_cert:
        # Read by the image's unprivileged user; a CA certificate is public.
        private_write(output / "database-ca" / "ca.crt", ca_cert.strip() + "\n", 0o644)
    private_write(output / "tls" / "origin.pem", origin_cert.strip() + "\n", 0o644)
    private_write(output / "tls" / "origin.key", origin_key.strip() + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    try:
        prepare(args.output, os.environ)
    except SettingError as error:
        sys.exit(f"Release not prepared: {error}")
    for warning in email_warnings(os.environ):
        # A GitHub Actions annotation: it shows on the run's summary page, not only in the log.
        print(f"::warning title=Email is off::{warning}")
    print(f"Release prepared in {args.output}")


if __name__ == "__main__":
    main()
