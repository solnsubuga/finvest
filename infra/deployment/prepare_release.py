"""Build one release bundle for deploy.sh from the GitHub environment's settings.

Ported from Fidiba's scripts/prepare_deployment.py. Each process gets a runtime file with only its
own database role, so the schema owner's password never reaches the API, worker or scheduler.
Settings are read from the environment (the deploy workflow passes them) and validated before
anything is written. Nothing secret is printed.

    python3 infra/deployment/prepare_release.py OUTPUT_DIR
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import stat
import sys
from collections.abc import Mapping
from pathlib import Path
from urllib.parse import quote

HERE = Path(__file__).resolve().parent
ENVIRONMENTS = ("staging", "production")
# Caddy and each colour's api and console meet on this network. The API believes X-Forwarded-For
# only from it (FINVEST_TRUSTED_PROXIES), and only Caddy sets that header.
EDGE_SUBNET = "172.30.0.0/24"
CA_PATH = "/etc/finvest/database-ca/ca.crt"
HOSTNAME = r"[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+"
IMAGE = r"[a-z0-9.:/_-]+@sha256:[a-f0-9]{64}"
ROLES = {"migrate": "migrator", "api": "app", "worker": "worker", "scheduler": "worker"}


class SettingError(ValueError):
    pass


def setting(env: Mapping[str, str], name: str, default: str | None = None, pattern: str | None = None) -> str:
    """A required setting, or its default, checked against a pattern. Values never appear in errors."""
    value = env.get(name, "").strip() or default
    if value is None or value == "":
        raise SettingError(f"{name} is not set")
    if pattern is not None and not re.fullmatch(pattern, value):
        raise SettingError(f"{name} is not valid")
    return value


def optional(env: Mapping[str, str], name: str) -> str:
    return env.get(name, "").strip()


def single_line(name: str, value: str) -> str:
    if "\n" in value or "\r" in value or "\0" in value:
        raise SettingError(f"{name} must be one line")
    return value


def private_write(path: Path, text: str, mode: int = 0o600) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write(text)
    os.chmod(path, mode)


def env_file(values: Mapping[str, str]) -> str:
    # Compose reads these with format: raw, so values are taken verbatim to the end of the line.
    return "".join(f"{name}={single_line(name, value)}\n" for name, value in values.items())


def database_url(env: Mapping[str, str], role: str) -> str:
    host = setting(env, "DATABASE_HOST", pattern=r"[a-zA-Z0-9][a-zA-Z0-9.-]*")
    port = setting(env, "DATABASE_PORT", "25060", r"[0-9]{1,5}")
    name = setting(env, "DATABASE_NAME", "finvest", r"[a-z_][a-z0-9_]*")
    password = single_line(f"DATABASE_{role.upper()}_PASSWORD", setting(env, f"DATABASE_{role.upper()}_PASSWORD"))
    return f"postgresql+asyncpg://finvest_{role}:{quote(password, safe='')}@{host}:{port}/{name}"


def site_caddy(site_domains: list[str]) -> str:
    canonical, *others = site_domains
    text = (
        "# Generated by prepare_release.py. The public website is not built yet.\n"
        f"{canonical} {{\n"
        "\timport origin_tls\n"
        "\timport common_headers\n"
        "\theader Cache-Control no-store\n"
        '\trespond "Finvest\'s new website is on its way." 503\n'
        "}\n"
    )
    if others:
        text += (
            f"{', '.join(others)} {{\n"
            "\timport origin_tls\n"
            f"\tredir https://{canonical}{{uri}} 308\n"
            "}\n"
        )
    return text


def prepare(output: Path, env: Mapping[str, str]) -> None:
    environment = setting(env, "DEPLOY_ENVIRONMENT", pattern="|".join(ENVIRONMENTS))
    rehearsal = optional(env, "FINVEST_REHEARSAL") == "true"

    api_domain = setting(env, "API_DOMAIN", pattern=HOSTNAME)
    admin_domain = setting(env, "ADMIN_DOMAIN", pattern=HOSTNAME)
    app_domain = setting(env, "APP_DOMAIN", pattern=HOSTNAME)
    site_domains = [d for d in re.split(r"[\s,]+", setting(env, "SITE_DOMAINS")) if d]
    for domain in site_domains:
        if not re.fullmatch(HOSTNAME, domain):
            raise SettingError("SITE_DOMAINS is not valid")
    hosts = [api_domain, admin_domain, app_domain, *site_domains]
    if len(set(hosts)) != len(hosts):
        raise SettingError("Every domain must be different")

    backend_image = setting(env, "BACKEND_IMAGE", pattern=IMAGE)
    console_image = setting(env, "CONSOLE_IMAGE", pattern=IMAGE)
    project = f"finvest-{environment}"
    # A rehearsal turns database TLS off, so it is accepted only with images from the throwaway
    # registry on the same machine, which a real deployment never uses.
    if rehearsal and not (backend_image.startswith("localhost:") and console_image.startswith("localhost:")):
        raise SettingError("FINVEST_REHEARSAL is for a local rehearsal only")

    origin_cert = setting(env, "ORIGIN_TLS_CERT")
    origin_key = setting(env, "ORIGIN_TLS_KEY")
    if "BEGIN CERTIFICATE" not in origin_cert or "PRIVATE KEY" not in origin_key:
        raise SettingError("ORIGIN_TLS_CERT and ORIGIN_TLS_KEY must be PEM")
    ca_cert = optional(env, "DATABASE_CA_CERT")
    if ca_cert and "BEGIN CERTIFICATE" not in ca_cert:
        raise SettingError("DATABASE_CA_CERT must be PEM")
    if not ca_cert and not rehearsal:
        raise SettingError("DATABASE_CA_CERT is not set")

    # Validate every database setting before writing anything.
    urls = {service: database_url(env, role) for service, role in ROLES.items()}

    database = {"FINVEST_LOG_FORMAT": "json"}
    if rehearsal:
        database["FINVEST_DATABASE_SSL_MODE"] = "disable"
    else:
        database["FINVEST_DATABASE_SSL_MODE"] = "verify-full"
        database["FINVEST_DATABASE_SSL_ROOT_CERT"] = CA_PATH

    storage = {
        name: single_line(name, optional(env, name))
        for name in (
            "FINVEST_OBJECT_STORAGE_BUCKET",
            "FINVEST_OBJECT_STORAGE_ENDPOINT",
            "FINVEST_OBJECT_STORAGE_REGION",
            "FINVEST_OBJECT_STORAGE_ACCESS_KEY_ID",
            "FINVEST_OBJECT_STORAGE_SECRET_ACCESS_KEY",
        )
        if optional(env, name)
    }

    # Sign-in settings (backend identity module). The client passkey site is the zone in
    # production, so passkeys work on the web and in the phone apps; staging keeps its own.
    client_site = site_domains[0] if environment == "production" else app_domain
    api = {
        **database,
        "FINVEST_DATABASE_URL": urls["api"],
        "FINVEST_TRUSTED_PROXIES": json.dumps([EDGE_SUBNET]),
        "FINVEST_CLIENT_ALLOWED_ORIGINS": json.dumps([f"https://{app_domain}"]),
        "FINVEST_STAFF_ALLOWED_ORIGINS": json.dumps([f"https://{admin_domain}"]),
        "FINVEST_CLIENT_PASSKEY_SITE": client_site,
        "FINVEST_STAFF_PASSKEY_SITE": admin_domain,
        "FINVEST_CLIENT_PASSKEY_APP_ORIGINS": optional(env, "FINVEST_CLIENT_PASSKEY_APP_ORIGINS") or "[]",
        **storage,
    }
    if optional(env, "FINVEST_AUTHENTICATOR_KEY"):
        api["FINVEST_AUTHENTICATOR_KEY"] = optional(env, "FINVEST_AUTHENTICATOR_KEY")

    worker = {**database, "FINVEST_DATABASE_URL": urls["worker"], **storage}
    for name in ("FINVEST_EMAIL_BACKEND", "FINVEST_EMAIL_FROM", "FINVEST_EMAIL_RESEND_API_KEY"):
        if optional(env, name):
            worker[name] = optional(env, name)

    runtime = {
        "migrate": {**database, "FINVEST_DATABASE_URL": urls["migrate"]},
        "api": api,
        "worker": worker,
        "scheduler": {**database, "FINVEST_DATABASE_URL": urls["scheduler"]},
    }

    release = {
        "FINVEST_DEPLOY_PROJECT": project,
        "BACKEND_IMAGE": backend_image,
        "CONSOLE_IMAGE": console_image,
        "FINVEST_API_DOMAIN": api_domain,
        "FINVEST_ADMIN_DOMAIN": admin_domain,
        "FINVEST_APP_DOMAIN": app_domain,
        "FINVEST_EDGE_SUBNET": EDGE_SUBNET,
        "FINVEST_STOP_BEFORE_MIGRATE": "true" if optional(env, "STOP_BEFORE_MIGRATE") == "true" else "false",
    }
    if rehearsal:
        release["FINVEST_CHECK_LOCAL"] = "true"
        for name in ("FINVEST_HTTP_PORT", "FINVEST_HTTPS_PORT", "FINVEST_BIND_ADDRESS"):
            if optional(env, name):
                release[name] = optional(env, name)

    if output.exists():
        shutil.rmtree(output)
    output.mkdir(mode=0o700, parents=True)
    for name in ("compose.yaml", "deploy.sh"):
        shutil.copy(HERE / name, output / name)
    (output / "deploy.sh").chmod(stat.S_IRWXU)
    (output / "edge").mkdir(mode=0o755)
    for name in ("Caddyfile", "upstreams.caddy"):
        shutil.copy(HERE / name, output / "edge" / name)
    (output / "edge" / "site.caddy").write_text(site_caddy(site_domains), encoding="utf-8")
    private_write(output / "release.env", env_file(release))
    for service, values in runtime.items():
        private_write(output / "runtime" / f"{service}.env", env_file(values))
    (output / "database-ca").mkdir(mode=0o755)
    if ca_cert:
        # Read by the image's unprivileged user; a CA certificate is public.
        private_write(output / "database-ca" / "ca.crt", ca_cert.strip() + "\n", 0o644)
    private_write(output / "tls" / "origin.pem", origin_cert.strip() + "\n", 0o644)
    private_write(output / "tls" / "origin.key", origin_key.strip() + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    try:
        prepare(args.output, os.environ)
    except SettingError as error:
        sys.exit(f"Release not prepared: {error}")
    print(f"Release prepared in {args.output}")


if __name__ == "__main__":
    main()
